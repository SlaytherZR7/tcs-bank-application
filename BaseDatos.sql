-- =============================================================================
-- BaseDatos.sql — Esquema de base de datos de la solución bancaria
-- =============================================================================
-- Cada microservicio tiene su propia base PostgreSQL (database per service):
--   * clientdb  -> client-service  (Persona/Cliente)
--   * accountdb -> account-service (Cuenta, Movimiento y proyección local de Cliente)
-- No existen claves foráneas entre bases: account-service recibe los datos del
-- cliente por eventos de RabbitMQ y los guarda en client_projection.
--
-- En Docker Compose NO hace falta ejecutar este script: Flyway aplica las mismas
-- migraciones (src/main/resources/db/migration) al arrancar cada servicio.
-- Este archivo reúne esas migraciones para crear el esquema manualmente:
--
--   psql -U postgres -f BaseDatos.sql
--
-- Si se usa este script, cada servicio debe arrancar con
-- SPRING_FLYWAY_BASELINE_ON_MIGRATE=true y SPRING_FLYWAY_BASELINE_VERSION=<última versión>
-- para que Flyway no intente recrear las tablas.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- client-service
-- -----------------------------------------------------------------------------
CREATE DATABASE clientdb;
\connect clientdb

-- V1__create_clients.sql
CREATE TABLE clients
(
    client_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    gender         VARCHAR(30)  NOT NULL,
    age            INTEGER      NOT NULL CHECK (age BETWEEN 1 AND 130),
    identification VARCHAR(20)  NOT NULL,
    address        VARCHAR(255) NOT NULL,
    phone          VARCHAR(20)  NOT NULL,
    password_hash  VARCHAR(60)  NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED')),
    CONSTRAINT uk_clients_identification UNIQUE (identification)
);

-- -----------------------------------------------------------------------------
-- account-service
-- -----------------------------------------------------------------------------
CREATE DATABASE accountdb;
\connect accountdb

-- V1__create_accounts_and_client_projection.sql
CREATE TABLE client_projection
(
    client_id     BIGINT PRIMARY KEY,
    client_name   VARCHAR(100) NOT NULL,
    client_status VARCHAR(10)  NOT NULL CHECK (client_status IN ('ACTIVE', 'INACTIVE', 'DELETED')),
    last_event_id VARCHAR(36)  NOT NULL,
    last_event_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE accounts
(
    account_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number  VARCHAR(50) NOT NULL
        CHECK (account_number ~ '^[0-9]{1,50}$'),
    account_type    VARCHAR(20) NOT NULL CHECK (account_type IN ('SAVINGS', 'CHECKING')),
    initial_balance NUMERIC(19, 2) NOT NULL CHECK (initial_balance >= 0),
    current_balance NUMERIC(19, 2) NOT NULL CHECK (current_balance >= 0),
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED')),
    client_id       BIGINT NOT NULL,
    CONSTRAINT uk_accounts_account_number UNIQUE (account_number),
    CONSTRAINT fk_accounts_client_projection
        FOREIGN KEY (client_id) REFERENCES client_projection (client_id)
);

CREATE INDEX idx_accounts_client_id ON accounts (client_id);

-- V2__create_movements.sql
CREATE TABLE movements
(
    movement_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date              TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    movement_type              VARCHAR(10)    NOT NULL CHECK (movement_type IN ('INCOME', 'EXPENSE')),
    amount                     NUMERIC(19, 2) NOT NULL CHECK (amount <> 0),
    resulting_balance          NUMERIC(19, 2) NOT NULL CHECK (resulting_balance >= 0),
    account_id                 BIGINT         NOT NULL,
    correction_of_movement_id  BIGINT,
    CONSTRAINT fk_movements_account
        FOREIGN KEY (account_id) REFERENCES accounts (account_id),
    CONSTRAINT fk_movements_correction_of
        FOREIGN KEY (correction_of_movement_id) REFERENCES movements (movement_id)
);

CREATE INDEX idx_movements_account_id        ON movements (account_id);
CREATE INDEX idx_movements_date              ON movements (movement_date);
CREATE INDEX idx_movements_correction_of_id  ON movements (correction_of_movement_id);

-- V3__default_movement_date.sql
ALTER TABLE movements
    ALTER COLUMN movement_date SET DEFAULT (now() AT TIME ZONE 'America/Guayaquil');

