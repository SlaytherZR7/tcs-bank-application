CREATE TABLE movements
(
    movement_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date              TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    movement_type              VARCHAR(10)    NOT NULL CHECK (movement_type IN ('INCOME', 'EXPENSE')),
    amount                     NUMERIC(19, 2) NOT NULL CHECK (amount <> 0),
    resulting_balance          NUMERIC(19, 2) NOT NULL CHECK (resulting_balance >= 0),
    account_id                 BIGINT         NOT NULL,
    correction_of_movement_id  BIGINT,
    CONSTRAINT fk_movements_account
        FOREIGN KEY (account_id) REFERENCES accounts (account_id),
    CONSTRAINT fk_movements_correction_of
        FOREIGN KEY (correction_of_movement_id) REFERENCES movements (movement_id)
);

CREATE INDEX idx_movements_account_id        ON movements (account_id);
CREATE INDEX idx_movements_date              ON movements (movement_date);
CREATE INDEX idx_movements_correction_of_id  ON movements (correction_of_movement_id);
